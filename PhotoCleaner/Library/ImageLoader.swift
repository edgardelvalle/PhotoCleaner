import Photos
import UIKit
import ImageIO

enum ImageLoader {
    static let thumbnails = PHCachingImageManager()

    /// Loads one image of roughly `side` pixels. The handler fires once with
    /// `.highQualityFormat`, which keeps the continuation simple.
    static func image(
        for asset: PHAsset,
        side: CGFloat,
        manager: PHImageManager = PHImageManager.default(),
        allowNetwork: Bool = true
    ) async -> UIImage? {
        await withCheckedContinuation { continuation in
            let options = PHImageRequestOptions()
            options.deliveryMode = .highQualityFormat
            options.resizeMode = .fast
            options.isNetworkAccessAllowed = allowNetwork
            manager.requestImage(
                for: asset,
                targetSize: CGSize(width: side, height: side),
                contentMode: .aspectFit,
                options: options
            ) { image, _ in
                continuation.resume(returning: image)
            }
        }
    }
}

extension CGImagePropertyOrientation {
    init(_ orientation: UIImage.Orientation) {
        switch orientation {
        case .up: self = .up
        case .upMirrored: self = .upMirrored
        case .down: self = .down
        case .downMirrored: self = .downMirrored
        case .left: self = .left
        case .leftMirrored: self = .leftMirrored
        case .right: self = .right
        case .rightMirrored: self = .rightMirrored
        @unknown default: self = .up
        }
    }
}
